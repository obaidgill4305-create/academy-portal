<?php
require __DIR__ . '/db.php';
require_login();

$method = $_SERVER['REQUEST_METHOD'];

const SELECT_COLS = "id, roll, name, father, phone, program_type AS programType, class, stream,
    batch, start_date AS startDate, end_date AS endDate, course_status AS courseStatus,
    fee_type AS feeType, monthly_fee AS monthlyFee, admission_date AS admissionDate";

function cast_student(&$r) {
    $r['monthlyFee'] = (float)$r['monthlyFee'];
    $r['roll'] = (int)$r['roll'];
}

if ($method === 'GET') {
    $stmt = $pdo->query("SELECT " . SELECT_COLS . " FROM students ORDER BY roll ASC");
    $rows = $stmt->fetchAll(PDO::FETCH_ASSOC);
    foreach ($rows as &$r) cast_student($r);
    echo json_encode($rows);
    exit;
}

if ($method === 'POST') {
    // Add a new student. Roll number is auto-generated by MySQL.
    $data = read_json_body();
    $id = 'stu_' . bin2hex(random_bytes(6));
    $programType = ($data['programType'] ?? 'academic') === 'skill' ? 'skill' : 'academic';
    $feeType = ($data['feeType'] ?? 'monthly') === 'one_time' ? 'one_time' : 'monthly';
    $courseStatus = ($data['courseStatus'] ?? 'ongoing') === 'completed' ? 'completed' : 'ongoing';

    $stmt = $pdo->prepare("INSERT INTO students
        (id, name, father, phone, program_type, class, stream, batch, start_date, end_date, course_status, fee_type, monthly_fee, admission_date)
        VALUES (:id, :name, :father, :phone, :ptype, :class, :stream, :batch, :sdate, :edate, :cstatus, :ftype, :fee, :adate)");
    $stmt->execute([
        ':id'      => $id,
        ':name'    => trim($data['name'] ?? ''),
        ':father'  => trim($data['father'] ?? ''),
        ':phone'   => trim($data['phone'] ?? ''),
        ':ptype'   => $programType,
        ':class'   => $data['class'] ?? '',
        ':stream'  => $data['stream'] ?? '',
        ':batch'   => $data['batch'] ?? '',
        ':sdate'   => !empty($data['startDate']) ? $data['startDate'] : null,
        ':edate'   => !empty($data['endDate']) ? $data['endDate'] : null,
        ':cstatus' => $courseStatus,
        ':ftype'   => $feeType,
        ':fee'     => (float)($data['monthlyFee'] ?? 0),
        ':adate'   => date('Y-m-d'),
    ]);

    $stmt2 = $pdo->prepare("SELECT " . SELECT_COLS . " FROM students WHERE id = ?");
    $stmt2->execute([$id]);
    $row = $stmt2->fetch(PDO::FETCH_ASSOC);
    cast_student($row);
    echo json_encode($row);
    exit;
}

if ($method === 'PUT') {
    // Update an existing student's details. Roll number and id never change.
    $id = $_GET['id'] ?? '';
    if (!$id) { http_response_code(400); echo json_encode(['error' => 'Missing id']); exit; }
    $data = read_json_body();
    $programType = ($data['programType'] ?? 'academic') === 'skill' ? 'skill' : 'academic';
    $feeType = ($data['feeType'] ?? 'monthly') === 'one_time' ? 'one_time' : 'monthly';
    $courseStatus = ($data['courseStatus'] ?? 'ongoing') === 'completed' ? 'completed' : 'ongoing';

    $stmt = $pdo->prepare("UPDATE students SET
        name=:name, father=:father, phone=:phone, program_type=:ptype, class=:class, stream=:stream,
        batch=:batch, start_date=:sdate, end_date=:edate, course_status=:cstatus, fee_type=:ftype, monthly_fee=:fee
        WHERE id=:id");
    $stmt->execute([
        ':name'    => trim($data['name'] ?? ''),
        ':father'  => trim($data['father'] ?? ''),
        ':phone'   => trim($data['phone'] ?? ''),
        ':ptype'   => $programType,
        ':class'   => $data['class'] ?? '',
        ':stream'  => $data['stream'] ?? '',
        ':batch'   => $data['batch'] ?? '',
        ':sdate'   => !empty($data['startDate']) ? $data['startDate'] : null,
        ':edate'   => !empty($data['endDate']) ? $data['endDate'] : null,
        ':cstatus' => $courseStatus,
        ':ftype'   => $feeType,
        ':fee'     => (float)($data['monthlyFee'] ?? 0),
        ':id'      => $id,
    ]);

    $stmt2 = $pdo->prepare("SELECT " . SELECT_COLS . " FROM students WHERE id = ?");
    $stmt2->execute([$id]);
    $row = $stmt2->fetch(PDO::FETCH_ASSOC);
    cast_student($row);
    echo json_encode($row);
    exit;
}

if ($method === 'DELETE') {
    // Deleting a student also removes their attendance & fee records (ON DELETE CASCADE)
    $id = $_GET['id'] ?? '';
    if (!$id) { http_response_code(400); echo json_encode(['error' => 'Missing id']); exit; }
    $stmt = $pdo->prepare("DELETE FROM students WHERE id = ?");
    $stmt->execute([$id]);
    echo json_encode(['success' => true]);
    exit;
}

http_response_code(405);
echo json_encode(['error' => 'Method not allowed']);
